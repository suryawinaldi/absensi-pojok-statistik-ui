import argparse
import json
import tempfile
from datetime import date
from pathlib import Path
from playwright.sync_api import sync_playwright
parser = argparse.ArgumentParser(description='Browser smoke tests for the static admin prototype.')
parser.add_argument('--base-url', default='http://127.0.0.1:8000')
parser.add_argument('--screenshots', default=None)
args = parser.parse_args()
base_url = args.base_url.rstrip('/')
out = Path(args.screenshots or tempfile.mkdtemp(prefix='pojok-prototype-'))
out.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1100},device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(base_url + '/prototype/',wait_until='networkidle')
    today = date.fromisoformat(page.evaluate('TODAY'))
    next_month = date(today.year + (today.month == 12), today.month % 12 + 1, 1)
    shift_date = next_month.replace(day=10).isoformat()
    post_date = next_month.replace(day=11).isoformat()
    page.get_by_role('heading',name='Selamat datang, Admin.').wait_for()
    page.screenshot(path=str(out/'desktop-home.png'),full_page=True)
    page.get_by_role('link',name='Direktori Agen').click()
    page.get_by_label('Cari agen').fill('Nadia')
    assert page.locator('.agent-card').count()==1
    page.locator('.agent-card').click()
    page.get_by_role('heading',name='Profil agen',exact=True).wait_for()
    page.get_by_label('Foto profil').set_input_files(str(out/'desktop-home.png'))
    page.locator('.profile-hero img').wait_for()
    page.get_by_role('button',name='Edit profil').click()
    page.get_by_label('Jabatan',exact=True).fill('Ketua Pojok Statistik')
    page.get_by_role('button',name='Simpan profil').click()
    assert page.locator('.profile-hero').inner_text().find('Ketua Pojok Statistik')>=0
    page.get_by_role('button',name='Tutup panel').click()
    page.reload()
    page.get_by_label('Cari agen').fill('Nadia')
    page.locator('.agent-card img').wait_for()
    page.get_by_label('Cari agen').fill('')
    page.get_by_role('button',name='Tambah agen',exact=True).click()
    page.get_by_label('Nama lengkap').fill('Agen Uji')
    page.get_by_label('Jabatan',exact=True).fill('Anggota')
    page.get_by_role('button',name='Simpan profil').click()
    page.locator('dialog').get_by_role('heading',name='Agen Uji',exact=True).wait_for()
    page.get_by_role('button',name='Tutup panel').click()
    page.get_by_role('link',name='Jadwal & Kehadiran',exact=True).click()
    page.get_by_role('button',name='Tambah penugasan').click()
    page.get_by_label('Agen',exact=True).select_option(label='Agen Uji')
    page.get_by_label('Tanggal',exact=True).fill(shift_date)
    page.get_by_role('button',name='Simpan penugasan').click()
    page.get_by_role('button',name='Catat',exact=True).click()
    page.get_by_label('Status kehadiran').select_option('Hadir')
    page.get_by_label('Jam hadir (WIB)',exact=True).fill('10:05')
    page.get_by_role('button',name='Simpan kehadiran').click()
    assert '10:05' in page.locator('tbody').inner_text()
    page.get_by_role('link',name='Konten & Publikasi').click()
    page.locator('#toast').evaluate("el => el.classList.remove('show')")
    page.screenshot(path=str(out/'desktop-calendar.png'),full_page=True)
    page.get_by_role('button',name='Buat konten',exact=True).click()
    page.get_by_label('Judul konten').fill('Konten Uji Kalender')
    page.get_by_label('Tanggal publikasi').fill(post_date)
    page.get_by_label('Jam publikasi (WIB)').fill('18:35')
    page.get_by_label('Caption',exact=True).fill('Caption contoh untuk pengujian.')
    page.get_by_label('Gambar / slide carousel').set_input_files(str(out/'desktop-home.png'))
    page.locator('#draft-images img').wait_for()
    page.get_by_role('button',name='Simpan konten',exact=True).click()
    page.get_by_role('button',name='Konten Uji Kalender, 18:35 WIB, Ide').click()
    assert 'Caption contoh untuk pengujian.' in page.locator('.content-caption').inner_text()
    page.get_by_role('button',name='Edit konten').click()
    page.get_by_label('Status',exact=True).select_option('Terbit')
    page.get_by_role('button',name='Simpan konten',exact=True).click()
    assert page.locator('#post-form').is_visible()
    page.get_by_label('Tautan postingan Instagram').fill('https://example.com/post')
    page.get_by_role('button',name='Simpan konten',exact=True).click()
    assert page.locator('#post-form').is_visible()
    page.get_by_label('Tautan postingan Instagram').fill('https://www.instagram.com/p/demo/')
    page.get_by_role('button',name='Simpan konten',exact=True).click()
    page.reload()
    page.get_by_role('button',name='Bulan berikutnya',exact=True).click()
    page.get_by_role('button',name='Konten Uji Kalender, 18:35 WIB, Terbit').click()
    page.get_by_role('link',name='Buka di Instagram').wait_for()
    page.get_by_role('button',name='Hapus konten',exact=True).click()
    page.get_by_role('button',name='Hapus konten',exact=True).click()
    assert page.get_by_role('button',name='Konten Uji Kalender, 18:35 WIB, Terbit').count()==0
    # Fresh mobile context, seeded records, no edits from the desktop workflow.
    mobile=browser.new_page(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
    mobile.on('pageerror',lambda e:errors.append(str(e)))
    for route in ['beranda','agen','kehadiran','konten']:
        mobile.goto(base_url + '/prototype/#'+route,wait_until='networkidle')
        assert mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth'),route+' horizontal overflow'
        mobile.screenshot(path=str(out/f'mobile-{route}.png'),full_page=True)
    mobile.get_by_role('button',name='Buat konten',exact=True).click()
    mobile.get_by_label('Judul konten').fill('Mobile draft')
    mobile.get_by_role('button',name='Tutup panel').click()
    assert not mobile.locator('dialog').is_visible()
    assert not errors,errors
    print(json.dumps({'passed':['dashboard','agent search','agent photo upload','profile edit and persistence','new agent','dated assignment','attendance recording','content creation with image','caption persistence','publication URL validation','content edit and deletion','four mobile routes without overflow','mobile dialog'],'page_errors':errors,'screenshots':str(out)}))
    browser.close()
